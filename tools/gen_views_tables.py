#!/usr/bin/env python3
"""Generate src/views/tables.rs: code points matched by artifacts._OBFUSCATED_ACTION_START_PATTERN.

Usage: python3 tools/gen_views_tables.py > src/views/tables.rs   (needs SKILLSPECTOR_SRC, see tools/README.md)
"""
import _ssimport  # noqa: F401
import skillspector.artifacts as a
import unicodedata

assert unicodedata.unidata_version == "15.1.0"
pat = a._OBFUSCATED_ACTION_START_PATTERN
out, start, prev = [], None, None
for c in range(0x110000):
    if 0xD800 <= c <= 0xDFFF:
        continue
    if pat.fullmatch(chr(c)):
        if start is None:
            start = c
        elif c != prev + 1:
            out.append((start, prev))
            start = c
        prev = c
    elif start is not None:
        out.append((start, prev))
        start = None
if start is not None:
    out.append((start, prev))
print("// @generated by tools/gen_views_tables.py -- do not edit by hand.\n")
print("/// Code points matched by `_OBFUSCATED_ACTION_START_PATTERN` (sorted inclusive ranges).")
print("pub const ACTION_START: &[(u32, u32)] = &[")
for lo, hi in out:
    print(f"    (0x{lo:X}, 0x{hi:X}),")
print("];")
