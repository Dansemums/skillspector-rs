#!/usr/bin/env python3
"""Generate src/unicode_tables.rs from this machine's Python (must be Unicode 15.1.0).

Usage: SKILLSPECTOR_SRC=<checkout>/src python3.13 tools/gen_unicode.py [path/to/unicode_confusables.py] > src/unicode_tables.rs
The confusables skeleton is copied verbatim from SkillSpector (its own pinned Unicode 17 data).
"""
import importlib.util
import os
import sys
import unicodedata

assert unicodedata.unidata_version == "15.1.0", unicodedata.unidata_version

CONF = (sys.argv[1] if len(sys.argv) > 1
        else os.path.join(os.environ.get("SKILLSPECTOR_SRC", "."), "skillspector", "unicode_confusables.py"))
spec = importlib.util.spec_from_file_location("unicode_confusables", CONF)
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)

SCALARS = [c for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF]


def ranges(pred):
    out, start, prev = [], None, None
    for c in SCALARS:
        if pred(chr(c)):
            if start is None:
                start = c
            elif c != prev + 1:
                out.append((start, prev))
                start = c
            prev = c
        elif start is not None and (c == prev + 1 or c > prev):
            out.append((start, prev))
            start = None
    if start is not None:
        out.append((start, prev))
    return out


def rs_str(s):
    return '"' + "".join(f"\\u{{{ord(ch):x}}}" for ch in s) + '"'


def emit_ranges(name, rs):
    print(f"pub static {name}: &[(u32, u32)] = &[")
    line = "   "
    for lo, hi in rs:
        item = f" (0x{lo:X}, 0x{hi:X}),"
        if len(line) + len(item) > 110:
            print(line)
            line = "   "
        line += item
    print(line)
    print("];")


def emit_map(name, pairs):
    print(f"pub static {name}: &[(u32, &str)] = &[")
    line = "   "
    for c, s in pairs:
        item = f" (0x{c:X}, {rs_str(s)}),"
        if len(line) + len(item) > 110:
            print(line)
            line = "   "
        line += item
    print(line)
    print("];")


# Default_Ignorable_Code_Point, copied from SkillSpector artifacts._DEFAULT_IGNORABLE_RANGES (15.1.0).
DEFAULT_IGNORABLE = [
    (0x00AD, 0x00AD), (0x034F, 0x034F), (0x061C, 0x061C), (0x115F, 0x1160), (0x17B4, 0x17B5),
    (0x180B, 0x180F), (0x200B, 0x200F), (0x202A, 0x202E), (0x2060, 0x206F), (0x3164, 0x3164),
    (0xFE00, 0xFE0F), (0xFEFF, 0xFEFF), (0xFFA0, 0xFFA0), (0xFFF0, 0xFFF8), (0x1BCA0, 0x1BCA3),
    (0x1D173, 0x1D17A), (0xE0000, 0xE0FFF),
]

cats = sorted({unicodedata.category(chr(c)) for c in SCALARS} - {"Cn"})
cat_index = {c: i for i, c in enumerate(cats)}
cat_ranges, start, prev, cur = [], None, None, None
for c in SCALARS:
    k = unicodedata.category(chr(c))
    if k == "Cn":
        k = None
    if k is not None and start is not None and k == cur and c == prev + 1:
        prev = c
        continue
    if start is not None:
        cat_ranges.append((start, prev, cur))
        start = None
    if k is not None:
        start, prev, cur = c, c, k
if start is not None:
    cat_ranges.append((start, prev, cur))

nfkc = [(c, unicodedata.normalize("NFKC", chr(c))) for c in SCALARS
        if unicodedata.normalize("NFKC", chr(c)) != chr(c)]
fold = [(c, chr(c).casefold()) for c in SCALARS if chr(c).casefold() != chr(c)]

print("// @generated by tools/gen_unicode.py -- do not edit by hand.")
print("#![allow(clippy::unreadable_literal)]")
print('#[cfg(test)]')
print(f'pub const UNIDATA_VERSION: &str = "{unicodedata.unidata_version}";')
emit_ranges("ALPHA", ranges(str.isalpha))
emit_ranges("ALNUM", ranges(str.isalnum))
emit_ranges("SPACE", ranges(str.isspace))
emit_ranges("PRINTABLE", ranges(str.isprintable))
emit_ranges("DEFAULT_IGNORABLE", DEFAULT_IGNORABLE)
print("pub static CATEGORY_NAMES: &[&str] = &[" + ", ".join(f'"{c}"' for c in cats) + "];")
print("pub static CATEGORY: &[(u32, u32, u8)] = &[")
line = "   "
for lo, hi, k in cat_ranges:
    item = f" (0x{lo:X}, 0x{hi:X}, {cat_index[k]}),"
    if len(line) + len(item) > 110:
        print(line)
        line = "   "
    line += item
print(line)
print("];")
emit_map("NFKC", nfkc)
emit_map("CASEFOLD", fold)
emit_map("CONFUSABLE", sorted(mod.ASCII_CONFUSABLE_SKELETON.items()))
